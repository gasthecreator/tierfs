#!/usr/bin/env python3
"""Generates tests/channel_kat.hpp: known-answer vectors for core/securechannel.cpp (protocol v4).

Independence: X25519 is implemented here from RFC 7748 (and checked against the RFC's own test vectors first); AES-GCM, HMAC and HKDF come
from scripts/gen_crypto_kat.py's from-scratch reference, which validates itself against NIST and RFC vectors when it is loaded. Nothing
in this file calls the C++ code or OpenSSL for the channel's cryptography.
"""
import hashlib, hmac, random, sys, os

here = os.path.dirname(os.path.abspath(__file__))
src = open(os.path.join(here, 'gen_crypto_kat.py')).read()
exec(compile(src[:src.index('# ---- vectors for the C++ tests')], 'gen_crypto_kat.py(reference)', 'exec'))

P = 2**255 - 19
def x25519(k, u):
    b = bytearray(k); b[0] &= 248; b[31] &= 127; b[31] |= 64
    k = int.from_bytes(b, 'little')
    ub = bytearray(u); ub[31] &= 127
    x1 = int.from_bytes(ub, 'little') % P
    x2, z2, x3, z3, swap = 1, 0, x1, 1, 0
    for t in reversed(range(255)):
        kt = (k >> t) & 1
        swap ^= kt
        if swap: x2, x3, z2, z3 = x3, x2, z3, z2
        swap = kt
        A = (x2 + z2) % P; AA = A * A % P; B = (x2 - z2) % P; BB = B * B % P; E = (AA - BB) % P
        C = (x3 + z3) % P; D = (x3 - z3) % P; DA = D * A % P; CB = C * B % P
        x3 = pow(DA + CB, 2, P); z3 = x1 * pow(DA - CB, 2, P) % P
        x2 = AA * BB % P; z2 = E * (AA + 121665 * E) % P
    if swap: x2, x3, z2, z3 = x3, x2, z3, z2
    return (x2 * pow(z2, P - 2, P) % P).to_bytes(32, 'little')

BASE = (9).to_bytes(32, 'little')
# RFC 7748 section 6.1 (Diffie-Hellman) test vectors
a = bytes.fromhex('77076d0a7318a57d3c16c17251b26645df4c2f87ebc0992ab177fba51db92c2a')
b = bytes.fromhex('5dab087e624a8a4b79e17f8b83800ee66f3bb1292618b6fd1c2f8b27ff88e0eb')
assert x25519(a, BASE).hex() == '8520f0098930a754748b7ddcb43ef75a0dbf3a0d26381af4eba4a98eaa9b4e6a', "X25519 reference: Alice public key"
assert x25519(b, BASE).hex() == 'de9edb7d7b7dc1b4d35b61c2ece435373f8343c85b78674dadfc7e146f882b4f', "X25519 reference: Bob public key"
assert x25519(a, x25519(b, BASE)).hex() == '4a5d9d5ba4ce2de1728e3bf480350f25e07e21c947d19e3376f09b3c1e161742', "X25519 reference: shared secret"
assert x25519(a, x25519(b, BASE)) == x25519(b, x25519(a, BASE))
# RFC 7748 section 5.2 first test vector
k = bytes.fromhex('a546e36bf0527c9d3b16154b82465edd62144c0ac1fc5a18506a2244ba449ac4')
u = bytes.fromhex('e6db6867583030db3594c1a424b15f7c726624ec26b3353b10a903a6d0ab1c4c')
assert x25519(k, u).hex() == 'c3da55379de9c6908e94ea4df28d084f32eccf03491c71f754b4075577a28552', "X25519 reference: RFC 7748 5.2 vector 1"
print("X25519 reference validated against RFC 7748")

rng = random.Random(20261012)
def rb(n): return bytes(rng.randrange(256) for _ in range(n))
def arr(name, v): return f"static const unsigned char {name}[] = {{{', '.join('0x%02x' % x for x in v) or '0'}}};\nstatic const size_t {name}_len = {len(v)};\n"
def H(m): return hashlib.sha256(m).digest()
def mac(k, m): return hmac.new(k, m, hashlib.sha256).digest()

VERSION = 4
psk = rb(32)
cseed, cnonce, sseed, snonce = rb(32), rb(32), rb(32), rb(32)
kid = mac(psk, b'tierfs-key-id')[:8]
cpub, spub = x25519(cseed, BASE), x25519(sseed, BASE)
shared = x25519(cseed, spub)
assert shared == x25519(sseed, cpub)
T = H(b'tierfs-chan-v4\x00' + VERSION.to_bytes(2, 'big') + kid + cpub + cnonce + spub + snonce)
okm = hkdf(psk + shared, T, b'tierfs-chan-v4 keys', 128)
c2s, s2c, cconf, sconf = okm[0:32], okm[32:64], okm[64:96], okm[96:128]
init = VERSION.to_bytes(2, 'big') + kid + cpub + cnonce
reply = spub + snonce + mac(sconf, T + b'S')
finish = mac(cconf, T + b'C')

def seal(key, ctr, typ, ident, payload):
    plain = bytes([typ]) + ident.to_bytes(4, 'big') + payload
    ln = len(plain) + 16
    aad = ln.to_bytes(4, 'big')
    ct, tag = gcm_encrypt(key, bytes(4) + ctr.to_bytes(8, 'big'), plain, aad)
    return aad + ct + tag

out = ["// GENERATED by scripts/gen_channel_kat.py -- do not edit.\n// clang-format off\n#pragma once\n#include <cstddef>\n\n"]
for name, v in [('chan_psk', psk), ('chan_cseed', cseed), ('chan_cnonce', cnonce), ('chan_sseed', sseed), ('chan_snonce', snonce),
                ('chan_keyid', kid), ('chan_cpub', cpub), ('chan_spub', spub), ('chan_shared', shared), ('chan_transcript', T),
                ('chan_init', init), ('chan_reply', reply), ('chan_finish', finish)]:
    out.append(arr('kat_' + name, v))
frames = [
    ('c2s_0', c2s, 0, 0x02, 7, b'hello tierfs'),
    ('c2s_1', c2s, 1, 0x13, 4294967295, b''),
    ('c2s_2', c2s, 2, 0x14, 0, bytes(range(256)) * 5),
    ('s2c_0', s2c, 0, 0x81, 1, b'OK'),
    ('s2c_1', s2c, 1, 0xFF, 7, (2).to_bytes(4, 'big') + (9).to_bytes(2, 'big') + b'not found'),
]
for name, key, ctr, typ, ident, payload in frames:
    out.append(arr('kat_chan_%s_payload' % name, payload))
    out.append(arr('kat_chan_%s_wire' % name, seal(key, ctr, typ, ident, payload)))
    out.append(f"static const unsigned kat_chan_{name}_type = {typ};\nstatic const unsigned long kat_chan_{name}_id = {ident}ul;\n")
open(os.path.join(here, '..', 'tests', 'channel_kat.hpp'), 'w').write(''.join(out))
print("wrote tests/channel_kat.hpp")
